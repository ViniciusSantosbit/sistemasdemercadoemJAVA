    private void jBpesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBpesquisarActionPerformed
        // TODO add your handling code here:
        try{
       Produto p = new Produto();
       ManterProduto ma = new ManterProduto();
        p.setCodigo(Integer.valueOf(jTpesquisar.getText()));
        ma.PesquisarRegistro(p);
            jTnome.setText(p.getNome());
            jTcodigoBarras.setText(p.getCodigoBarras());
            jTpreco.setText(String.valueOf(p.getPreco()));
            jTestoque.setText(String.valueOf(p.getEstoque()));
            selecionarCategoria(p.getCodigoCategoria());
        jTpesquisar.setEditable(false);
      }
      catch (Exception e){
            System.out.println("Erro " + e.getMessage());
       }
    }//GEN-LAST:event_jBpesquisarActionPerformed

    private void jBalterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBalterarActionPerformed
        // TODO add your handling code here:
        try{
      Produto p = new  Produto();
      ManterProduto ma = new ManterProduto();
      p.setCodigo(Integer.valueOf(jTpesquisar.getText()));
      p.setNome(jTnome.getText());
      p.setCodigoBarras(jTcodigoBarras.getText());
      p.setPreco(Double.parseDouble(jTpreco.getText().replace(",", ".")));
      p.setEstoque(Integer.parseInt(jTestoque.getText()));
      // pega o codigo que fica antes do " - " no combo (ex.: "1 - Bebidas")
      p.setCodigoCategoria(Integer.parseInt(jCcategoria.getSelectedItem().toString().split(" - ")[0]));
      ma.editarProduto(p);
      jTnome.setText("");
      jTcodigoBarras.setText("");
      jTpreco.setText("");
      jTestoque.setText("");
      jTpesquisar.setText("");
      jTpesquisar.setEditable(true);
      jTpesquisar.requestFocus();
      }catch(Exception e){
        JOptionPane.showMessageDialog(this,"Erro de : " + e.getMessage());
      }
    }//GEN-LAST:event_jBalterarActionPerformed

    // seleciona no combo a categoria do produto pesquisado
    private void selecionarCategoria(int codigo) {
        for (int i = 0; i < jCcategoria.getItemCount(); i++) {
            if (jCcategoria.getItemAt(i).startsWith(codigo + " - ")) {
                jCcategoria.setSelectedIndex(i);
            }
        }
    }

