    private void jBcadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBcadastrarActionPerformed
        // TODO add your handling code here:
        try {
            Produto p = new Produto();
            p.setNome(jTnome.getText());
            p.setCodigoBarras(jTcodigoBarras.getText());
            p.setPreco(Double.parseDouble(jTpreco.getText().replace(",", ".")));
            p.setEstoque(Integer.parseInt(jTestoque.getText()));
            // pega o codigo que fica antes do " - " no combo (ex.: "1 - Bebidas")
            p.setCodigoCategoria(Integer.parseInt(jCcategoria.getSelectedItem().toString().split(" - ")[0]));
            ManterProduto ma = new ManterProduto();
            try {
                if (!ma.inserir(p)) {
                    return;
                }
                if (aoCadastrar != null) {
                    aoCadastrar.accept(p);
                    dispose();
                    return;
                }
                jTnome.setText("");
                jTcodigoBarras.setText("");
                jTpreco.setText("");
                jTestoque.setText("");
                jTnome.requestFocus();
            } catch (Exception ex) {
                Logger.getLogger(CadastroProduto.class.getName()).log(Level.SEVERE, null, ex);
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Digite apenas numeros nos campos numericos.");
        }
    }//GEN-LAST:event_jBcadastrarActionPerformed

