    private void jBpesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBpesquisarActionPerformed
        // TODO add your handling code here:
        try{
       Funcionario f = new Funcionario();
       ManterFuncionario ma = new ManterFuncionario();
        f.setCodigo(Integer.valueOf(jTpesquisar.getText()));
        ma.PesquisarRegistro(f);
            jTnome.setText(f.getNome());
            jTcpf.setText(f.getCpf());
            jTtelefone.setText(f.getTelefone());
            jTcargo.setText(f.getCargo());
        jTpesquisar.setEditable(false);
      }
      catch (Exception e){
            System.out.println("Erro " + e.getMessage());
       }
    }//GEN-LAST:event_jBpesquisarActionPerformed

    private void jBalterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBalterarActionPerformed
        // TODO add your handling code here:
        try{
      Funcionario f = new  Funcionario();
      ManterFuncionario ma = new ManterFuncionario();
      f.setCodigo(Integer.valueOf(jTpesquisar.getText()));
      f.setNome(jTnome.getText());
      f.setCpf(jTcpf.getText());
      f.setTelefone(jTtelefone.getText());
      f.setCargo(jTcargo.getText());
      ma.editarFuncionario(f);
      jTnome.setText("");
      jTcpf.setText("");
      jTtelefone.setText("");
      jTcargo.setText("");
      jTpesquisar.setText("");
      jTpesquisar.setEditable(true);
      jTpesquisar.requestFocus();
      }catch(Exception e){
        JOptionPane.showMessageDialog(this,"Erro de : " + e.getMessage());
      }
    }//GEN-LAST:event_jBalterarActionPerformed

