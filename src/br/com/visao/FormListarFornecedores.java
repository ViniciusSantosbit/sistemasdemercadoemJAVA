    private void carregarRegistros() {
        try {
        Fornecedor f = new Fornecedor();
        ManterFornecedor ma = new ManterFornecedor();
        DefaultTableModel tabela = (DefaultTableModel) jTbf.getModel();
        tabela.setRowCount(0);// limpa a tabela antes de listar
        if (jTpesquisar.getText().equalsIgnoreCase("")){
        ArrayList<Fornecedor> lista = ma.PesquisarTudo();  //Vetor que recebe os Dados Traduzidos
        for (int i = 0; i < lista.size(); i++) {
            f = lista.get(i);
            tabela.addRow(new Object[]{f.getCodigo(), f.getRazaoSocial(), f.getCnpj(), f.getTelefone(), f.getEmail()});
        }
        }else{
          f.setCodigo(Integer.valueOf(jTpesquisar.getText()));
          ma.PesquisarRegistro(f);
          tabela.addRow(new Object[]{f.getCodigo(), f.getRazaoSocial(), f.getCnpj(), f.getTelefone(), f.getEmail()});
        }

        jTpesquisar.setText(null);
        jTpesquisar.requestFocus();
       }
       catch (Exception e){
            System.out.println("Erro " + e.getMessage());
       }
    }

