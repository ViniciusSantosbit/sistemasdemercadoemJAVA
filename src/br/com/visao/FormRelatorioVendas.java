    private void jBgerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBgerarActionPerformed
        // TODO add your handling code here:
        try {
            ManterVenda mv = new ManterVenda();
            ArrayList<Venda> vendas = mv.relatorio(converterData(jTinicio.getText()), converterData(jTfim.getText()));
            DefaultTableModel tabela = (DefaultTableModel) jTbrelatorio.getModel();
            tabela.setRowCount(0);
            double total = 0;
            int quantidade = 0;
            for (int i = 0; i < vendas.size(); i++) {
                Venda v = vendas.get(i);
                tabela.addRow(new Object[]{v.getCodigo(), v.getDataVenda(), v.getCpfCliente() == null ? "Nao informado" : v.getCpfCliente(),
                v.getNomeFuncionario(), v.getFormaPagamento(), v.getStatus(), String.format("R$ %.2f", v.getTotal())});
                if (v.getStatus().equals("FINALIZADA")) {// canceladas nao entram no total
                    total = total + v.getTotal();
                    quantidade++;
                }
            }
            jLresumo.setText(String.format("Vendas finalizadas: %d   |   Total vendido: R$ %.2f   |   Registros: %d", quantidade, total, vendas.size()));
        } catch (ArrayIndexOutOfBoundsException e) {
            JOptionPane.showMessageDialog(this, "Digite as datas no formato dd/mm/aaaa.");
        } catch (Exception e) {
            System.out.println("Erro " + e.getMessage());
        }
    }//GEN-LAST:event_jBgerarActionPerformed

