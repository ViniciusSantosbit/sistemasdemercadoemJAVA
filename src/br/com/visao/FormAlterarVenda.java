    private void jBpesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBpesquisarActionPerformed
        // TODO add your handling code here:
        try{
       Venda v = new Venda();
       ManterVenda mv = new ManterVenda();
        v.setCodigo(Integer.valueOf(jTpesquisar.getText()));
        mv.PesquisarRegistro(v);
        if (v.getCodigo() == 0) {
            return;
        }
        jTcpf.setText(v.getCpfCliente() == null ? "" : v.getCpfCliente());
        jCpagamento.setSelectedItem(v.getFormaPagamento());
        jCstatus.setSelectedItem(v.getStatus());
        // mostra os itens da venda
        DefaultTableModel tabela = (DefaultTableModel) jTbitens.getModel();
        tabela.setRowCount(0);
        ArrayList<ItemVenda> itens = mv.PesquisarItens(v.getCodigo());
        for (int i = 0; i < itens.size(); i++) {
            ItemVenda item = itens.get(i);
            tabela.addRow(new Object[]{item.getNomeProduto(), item.getQuantidade(),
                String.format("R$ %.2f", item.getPrecoUnitario()), String.format("R$ %.2f", item.getSubtotal())});
        }
        jTpesquisar.setEditable(false);
      }
      catch (Exception e){
            System.out.println("Erro " + e.getMessage());
       }
    }//GEN-LAST:event_jBpesquisarActionPerformed

    private void jBalterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBalterarActionPerformed
        // TODO add your handling code here:
        try{
      Venda v = new  Venda();
      ManterVenda mv = new ManterVenda();
      v.setCodigo(Integer.valueOf(jTpesquisar.getText()));
      String cpf = jTcpf.getText().replace(".", "").replace("-", "").trim();
      if (!cpf.equals("") && cpf.length() != 11) {
          JOptionPane.showMessageDialog(this, "CPF deve ter 11 numeros (ou deixe em branco).");
          return;
      }
      v.setCpfCliente(cpf.equals("") ? null : cpf);
      v.setFormaPagamento(jCpagamento.getSelectedItem().toString());
      v.setStatus(jCstatus.getSelectedItem().toString());
      mv.editarVenda(v);
      jTcpf.setText("");
      jTpesquisar.setText("");
      ((DefaultTableModel) jTbitens.getModel()).setRowCount(0);
      jTpesquisar.setEditable(true);
      jTpesquisar.requestFocus();
      }catch(Exception e){
        JOptionPane.showMessageDialog(this,"Erro de : " + e.getMessage());
      }
    }//GEN-LAST:event_jBalterarActionPerformed

